/**
 * البحث عن قصة قرآنية بواسطة النص المنطوق من المستخدم
 */
export function findStoryByQuery(queryText) {
  if (!queryText) return null;
  const clean = queryText
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[أإآء]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/[ىي]/g, 'ي')
    .replace(/ـ+/g, '')
    .replace(/[.,/#!$%^&*;:{}=\-_`~()؟?،]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

  const words = clean.split(/\s+/);
  const storyKeywords = ['قصه', 'قصة', 'حكايه', 'حكاية', 'سيره', 'سيرة', 'احكي', 'روايه', 'رواية', 'اخبار', 'خبر'];
  const hasStoryKeyword = words.some(w => storyKeywords.includes(w)) || clean.startsWith('احكي');
  const hasSurahKeyword = words.includes('سوره') || words.includes('سورة');

  // إذا كان الطلب صريحاً بسورة ("سورة كذا") ولا يحتوي على لفظ قصة أو حكاية، فهو طلب سورة وليس قصة
  if (hasSurahKeyword && !hasStoryKeyword) {
    return null;
  }

  // أسماء السور التي تتطابق أسماؤها مع الأنبياء أو مواضيع مشتركة
  const surahProphetNames = ['يوسف', 'نوح', 'ابراهيم', 'هود', 'يونس', 'محمد', 'لقمان', 'سبا', 'مريم', 'الكهف', 'الانبياء'];

  // 1. مطابقة مباشرة بالمعرفات والأسماء المستعارة
  for (const story of QURAN_STORIES) {
    if (clean === story.id) return story;
    
    for (const alias of story.aliases) {
      const cleanAlias = alias
        .replace(/[أإآء]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/[ىي]/g, 'ي')
        .trim();

      // إذا كان الاسم المستعار هو اسم سورة مفرد (مثل "يوسف" أو "نوح") فلا نطابق القصة إلا بطلب قصة صريح
      if (surahProphetNames.includes(cleanAlias) && !hasStoryKeyword) {
        continue;
      }

      if (clean === cleanAlias || clean === `قصه ${cleanAlias}` || words.includes(cleanAlias) || clean.includes(` ${cleanAlias}`) || clean.startsWith(`${cleanAlias} `)) {
        return story;
      }
    }
  }

  // 2. مطابقة بالاسم الرئيسي (إذا كان الطلب يتضمن لفظ قصة صريح)
  if (hasStoryKeyword) {
    for (const story of QURAN_STORIES) {
      const cleanName = story.name
        .replace(/[أإآء]/g, 'ا')
        .replace(/ة/g, 'ه')
        .replace(/[ىي]/g, 'ي');
      if (clean.includes(cleanName) || cleanName.includes(clean)) {
        return story;
      }
    }
  }

  return null;
}

/**
 * بناء طابور تلاوة الآيات زمنيّاً للقصة بالكامل
 * يحدد بدقة متى تكون الآيات متصلة (0ms Gapless) ومتى يحدث انتقال لمشهد أو سورة جديدة
 */
export function compileStoryPlaylist(story) {
  if (!story || !story.scenes) return [];

  const playlist = [];

  story.scenes.forEach((scene, sceneIndex) => {
    scene.passages.forEach((passage, passageIndex) => {
      const surah = SURAHS.find(s => s.id === passage.surahId);
      if (!surah) return;

      const start = passage.startAyah;
      const end = passage.endAyah || start;

      for (let a = start; a <= end; a++) {
        const prevTrack = playlist[playlist.length - 1];
        
        // هل هذا الموضع قفزة (سورة مختلفة أو آيات غير متتالية في نفس السورة)؟
        const isJump = !prevTrack || (prevTrack.surah.id !== surah.id) || (prevTrack.ayahNumber !== a - 1);

        playlist.push({
          surah: surah,
          ayahNumber: a,
          sceneTitle: scene.title,
          sceneIndex: sceneIndex,
          totalScenes: story.scenes.length,
          passageLabel: passage.label,
          storyId: story.id,
          storyName: story.name,
          isJump: isJump, // إذا كان True يتم إطلاق صوت الفاصل والمهلة، وإذا كان False يتم التبديل فوراً 0ms
          label: `${scene.title} • سورة ${surah.name} (${a})`
        });
      }
    });
  });

  return playlist;
}
